"""Lightweight Claude Code hooks: fast Ruff feedback and guards for risky actions.

Hooks receive the tool call as JSON on stdin. Exit code 2 sends stderr back to Claude
(blocking the call for PreToolUse); exit code 0 lets the action proceed. The hooks are
read-only, idempotent and never run the full test suite.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]

PROTECTED_FILES = {"uv.lock"}
PROTECTED_PATTERNS = (re.compile(r"(^|/)\.env(\.[^/]*)?$"),)
# Recursive deletion is only allowed for local, regenerable outputs.
DISPOSABLE_DIRS = ("artifacts", "dist", "build", "htmlcov", ".pytest_cache", ".ruff_cache")

DANGEROUS_COMMANDS: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(r"\bgit\s+push\b[^;&|]*(\s--force\b|\s-f\b|\s--force-with-lease\b)"),
        "force push rewrites remote history",
    ),
    (re.compile(r"\bgit\s+reset\s+[^;&|]*--hard\b"), "git reset --hard discards work"),
    (re.compile(r"\bgit\s+clean\s+[^;&|]*-[a-zA-Z]*f"), "git clean -f deletes untracked work"),
    (re.compile(r"\bgit\s+(commit|push)\b[^;&|]*--no-verify\b"), "--no-verify skips hooks"),
    (re.compile(r"\bgit\s+checkout\s+--\s+\.(\s|$)"), "checkout -- . discards all changes"),
)
RECURSIVE_RM = re.compile(r"\brm\s+(-[a-zA-Z]*[rR][a-zA-Z]*f?|-[a-zA-Z]*f[a-zA-Z]*[rR])\s+(.+)")


def read_event() -> dict[str, Any]:
    """Parse the hook payload; malformed input is treated as an empty event."""
    try:
        data = json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return {}
    return data if isinstance(data, dict) else {}


def tool_file(event: dict[str, Any]) -> Path | None:
    """Return the file targeted by an Edit/Write tool call, if any."""
    tool_input = event.get("tool_input")
    if not isinstance(tool_input, dict):
        return None
    value = tool_input.get("file_path")
    return Path(value) if isinstance(value, str) and value else None


def relative_to_root(path: Path) -> str:
    """Express a path relative to the repository using POSIX separators."""
    resolved = path if path.is_absolute() else ROOT / path
    try:
        return resolved.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return resolved.as_posix()


def protected_file_reason(path: Path) -> str | None:
    """Explain why a file must not be edited directly, or return None."""
    relative = relative_to_root(path)
    if relative in PROTECTED_FILES:
        return f"{relative} is generated by uv; change pyproject.toml and run `uv lock`."
    if any(pattern.search(relative) for pattern in PROTECTED_PATTERNS):
        return f"{relative} may hold secrets; the repository never stores credentials."
    return None


def _rm_targets_allowed(targets: str) -> bool:
    for raw in targets.split():
        if raw.startswith("-"):
            continue
        cleaned = raw.strip("'\"").rstrip("/")
        cleaned = cleaned.removeprefix("./")
        if not any(
            cleaned == folder or cleaned.startswith(folder + "/") for folder in DISPOSABLE_DIRS
        ):
            return False
    return True


def dangerous_command_reason(command: str) -> str | None:
    """Return why a shell command is blocked, or None when it may run."""
    for pattern, reason in DANGEROUS_COMMANDS:
        if pattern.search(command):
            return reason
    for segment in re.split(r"&&|\|\||;|\|", command):
        match = RECURSIVE_RM.search(segment)
        if match and not _rm_targets_allowed(match[2]):
            return "recursive rm outside disposable build/artifact folders"
    return None


def pre_edit(event: dict[str, Any]) -> int:
    """Block direct edits to generated or secret-bearing files."""
    path = tool_file(event)
    reason = protected_file_reason(path) if path else None
    if reason:
        print(f"MoanArt hook blocked edit: {reason}", file=sys.stderr)
        return 2
    return 0


def pre_bash(event: dict[str, Any]) -> int:
    """Block destructive Git and filesystem commands."""
    tool_input = event.get("tool_input")
    command = tool_input.get("command") if isinstance(tool_input, dict) else None
    reason = dangerous_command_reason(command) if isinstance(command, str) else None
    if reason:
        print(
            f"MoanArt hook blocked command: {reason}. Ask the user explicitly if it is intended.",
            file=sys.stderr,
        )
        return 2
    return 0


def post_edit(event: dict[str, Any]) -> int:
    """Run Ruff lint and format check on the edited Python file only."""
    path = tool_file(event)
    if path is None or path.suffix not in {".py", ".pyi"}:
        return 0
    target = path if path.is_absolute() else ROOT / path
    if not target.is_file() or not target.resolve().is_relative_to(ROOT):
        return 0
    problems = []
    for command in (["check", "--quiet"], ["format", "--check", "--quiet"]):
        result = subprocess.run(
            [sys.executable, "-m", "ruff", *command, str(target)],
            cwd=ROOT,
            check=False,
            capture_output=True,
            encoding="utf-8",
            errors="replace",
        )
        if result.returncode:
            output = (result.stdout + result.stderr).strip() or "would reformat"
            problems.append(f"ruff {command[0]}: {output}")
    if problems:
        print(f"Ruff issues in {relative_to_root(target)}:", file=sys.stderr)
        print("\n".join(problems), file=sys.stderr)
        return 2
    return 0


HANDLERS = {"pre-edit": pre_edit, "pre-bash": pre_bash, "post-edit": post_edit}


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1 or args[0] not in HANDLERS:
        print(f"usage: claude_hooks {{{'|'.join(HANDLERS)}}}", file=sys.stderr)
        return 1
    return HANDLERS[args[0]](read_event())


if __name__ == "__main__":
    raise SystemExit(main())
