"""Strict schema 1.0 of MoanArt documents (MOANART.md section 12, ADR-011).

Entry point: :func:`validate_document` turns untrusted JSON bytes or a mapping into a
frozen :class:`Document`, or raises a ``moanart.core`` error whose ``details`` locate
every problem by JSON Pointer. :func:`canonical_json` and :func:`snapshot_digest`
implement the canonical normalisation of section 14; :func:`document_json_schema`
generates the versioned JSON Schema stored in ``schemas/``. Masks and regions form a
reference DAG checked by :mod:`moanart.schema.references`; :func:`resolve_region`
resolves a semantic region by ID (ADR-022). A ``dither`` operation names two palette
colours and a clipping mask (ADR-025); an ``outline`` operation names one colour and
the mask it outlines (ADR-027); a ``shade`` operation names a ramp and ordered bands,
each with its own ID and mask (ADR-028); a ``material`` operation adds to those
bands the texture of a versioned preset, and a ``selective_outline`` operation an
outline whose authored segments take ramp steps from the same light (ADR-030).
Format versions are an explicit registry (:data:`DOCUMENT_MIGRATIONS`, only 1.0
and no migration); :func:`migrate_document` migrates a tree with registered pure
steps, and reading never migrates (ADR-031). ``animations`` declares finite
timelines whose frames carry a duration and typed overrides (visibility, geometry,
colour) of base IDs, evaluated by :mod:`moanart.animation` (ADR-032).
"""

